def test_checkpassword_rehash_update_sql_has_no_crypt_or_gen_salt(
    args, monkeypatch, echo_calls
):
    """The rehash UPDATE must NOT contain ``crypt(`` or ``gen_salt``.
    The hash is pre-computed by ``bbsengine6.util.encryptpassword``;
    the SQL is just ``set password=$1 where moniker=$2``.
    """
    cursor = _SpyCursor(stored_password=_LEGACY_MD5_HASH)
    _patch_connect(monkeypatch, cursor)

    libmember.checkpassword(args, "12345", membermoniker="jam", pool=Mock())

    update_calls = [
        (q, p) for q, p in cursor.calls
        if _render_query(q).lstrip().startswith("update ")
    ]
    assert len(update_calls) == 1, (
        f"expected exactly one UPDATE (the rehash); got {len(update_calls)}"
    )
    assert "crypt(" not in _render_query(update_calls[0][0])
    assert "gen_salt" not in _render_query(update_calls[0][0])


def _render_query(q):
    """Render a psycopg Composed/SQL object to its SQL text.

    str(Composed) returns a Python repr, not SQL. as_string(None)
    produces the actual SQL that would be sent to PG.
    """
    return (q.as_string(None) if hasattr(q, "as_string") else str(q)).lower()


def test_checkpassword_conn_pool_pattern_uses_existing_cursor(args, monkeypatch):
    """``cur=`` keyword bypasses connect entirely. ``database.connect``
    must NOT be invoked when the caller supplies a cursor."""
    cursor = _SpyCursor(stored_password=_HEALTHY_BCRYPT_HASH)

    connect_called = []

    def _fail_connect(*a, **kw):
        connect_called.append((a, kw))
        raise RuntimeError(
            "database.connect must not be called when cur= is supplied"
        )

    monkeypatch.setattr(database, "connect", _fail_connect)

    result = libmember.checkpassword(
        args, "12345", membermoniker="jam", cur=cursor
    )

    assert result is True
    assert connect_called == [], (
        "cur= must short-circuit the connect path; database.connect "
        "was called"
    )
    assert cursor._select_count == 2
    assert cursor._update_count == 0


def test_checkpassword_conn_pool_pattern_uses_existing_conn(args, monkeypatch):
    """``conn=`` reuses the caller's connection. ``database.connect``
    must NOT be invoked; the spy conn is used directly."""
    cursor = _SpyCursor(stored_password=_HEALTHY_BCRYPT_HASH)
    conn = _SpyConn(cursor)

    connect_called = []
    monkeypatch.setattr(
        database, "connect",
        lambda *a, **kw: connect_called.append((a, kw)) or (_ for _ in ()).throw(
            RuntimeError("connect must not be called when conn= is supplied")
        ),
    )

    result = libmember.checkpassword(
        args, "12345", membermoniker="jam", conn=conn
    )

    assert result is True
    assert connect_called == []


