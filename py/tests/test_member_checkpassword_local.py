"""
Unit tests for ``bbsengine6.member.checkpassword`` and
``bbsengine6.member.rehashpassword`` — the local-verify and
opportunistic-rehash path that mirrors ``bbsengine6\\member\\lib\\
checkpassword`` and ``bbsengine6\\member\\lib\\rehashpassword`` on
the PHP side.

Pins (after the 2026-08-23 rewrite that removed the PG
``crypt(plaintext, password)`` round-trip):

  - checkpassword issues ONE SELECT for the stored hash. The SQL
    MUST NOT contain ``crypt(`` (that was the round-trip signal).
  - The verify runs locally: stdlib ``crypt(plaintext, stored)``
    first (handles ``$1$`` MD5-crypt + ``$5$``/``$6$`` SHA-crypt +
    ``$2[abxy]$`` bcrypt in one path), passlib ``bcrypt.verify``
    as a bcrypt-specific fallback.
  - On successful verify of a legacy hash, ``checkpassword``
    triggers ``rehashpassword`` to rewrite the column to a fresh
    ``$2b$06$...`` bcrypt value. Healthy hashes are not rewritten.
  - ``rehashpassword`` is a single UPDATE — no SELECT round-trip,
    no ``gen_salt`` in the wire SQL. The hash is produced locally by
    ``bbsengine6.util.encryptpassword`` (which delegates to
    ``bbsengine6.password.hash_password``).
  - CONN_POOL_PATTERN: cur=/conn=/pool=/args= are all honoured in
    priority order.

Why a separate file from ``test_member_audit_password_hash.py``:

  The audit-test file pins the per-auth diagnostic (``audit_-
  password_hash`` is invoked on the same cursor, warning levels
  fire on legacy hashes). This file pins the verify + rehash
  contract. The two concerns diverge enough that combining them
  would obscure each test's intent. Both files import the
  ``bbsengine6.member.lib`` module — they are siblings, not a
  hierarchy.
"""

import contextlib
