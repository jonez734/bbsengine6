class _SpyCursor:
    """Cursor stand-in for the local-verify + rehash test path.

    Behaves like a real psycopg cursor for the small subset that
    ``checkpassword`` and ``rehashpassword`` use:

      - ``execute(query, params)`` records the call. The first
        SELECT (row fetch) sets ``_row`` so ``fetchone()`` returns
        it on the next call. Subsequent UPDATEs (rehash) just
        increment ``_update_count`` and set ``rowcount`` to 1.
      - ``fetchone()`` returns the stored password row once, then
        None on the second call (mimics PG's read-once cursor
        semantics for the SELECT case).
      - ``rowcount`` reflects the last UPDATE (1 for success,
        0 for no row matched).

    Mirrors the ``_SpyCursor`` pattern in
    ``test_console_member_add_edit.py`` and
    ``test_member_audit_password_hash.py``.
    """

    def __init__(self, stored_password=None, rowcount=1, return_row=True):
        self._row = (
            {"password": stored_password} if return_row else None
        )
        self._rowcount = rowcount
        self._update_count = 0
        self._select_count = 0
        self.calls = []  # list of (query, params)

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False

    def execute(self, query, params=None):
        self.calls.append((query, params))
        rendered = (
            query.as_string(None)
            if hasattr(query, "as_string")
            else str(query)
        ).lower()
        if rendered.lstrip().startswith("select "):
            self._select_count += 1
        elif rendered.lstrip().startswith("update "):
            self._update_count += 1

    def fetchone(self):
        # The SELECT in checkpassword fetches exactly one row; the
        # rehash UPDATE never calls fetchone. So fetchone is called
        # at most once and always returns the row we stashed.
        return self._row

    @property
    def rowcount(self):
        return self._rowcount

    @rowcount.setter
    def rowcount(self, value):
        self._rowcount = value


class _SpyConn:
    """Connection stand-in that emits a single ``_SpyCursor``."""

    def __init__(self, cursor):
        self._cursor = cursor
        self.committed = False
        self.rolled_back = False

    def cursor(self, **kw):
        return self._cursor

    def commit(self):
        self.committed = True

    def rollback(self):
        self.rolled_back = False

    @property
    def autocommit(self):
        return False

    @autocommit.setter
    def autocommit(self, value):
        pass

    @property
    def pgconn(self):
        m = Mock()
        m.transaction_status = 0
        return m


