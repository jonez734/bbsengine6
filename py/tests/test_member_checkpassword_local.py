# Real bcrypt hash for plaintext "12345" generated via passlib with a
# deterministic salt so the test value is stable across runs. The
# salt is 22 base64-ish chars; the cost is 4 for fast test execution.
try:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        from passlib.hash import bcrypt as _pl_bcrypt

    _HEALTHY_BCRYPT_HASH = _pl_bcrypt.using(
        rounds=4, salt="abcdefghijklmnopqrstuv"
    ).hash("12345")
except ImportError:  # pragma: no cover
    pytest.skip("passlib not installed; cannot exercise verify path", allow_module_level=False)
    _HEALTHY_BCRYPT_HASH = "$2b$04$" + "Z" * 22 + "." * 31


# Real $1$ MD5-crypt hash for plaintext "12345" generated by stdlib
# crypt with a deterministic salt. The resulting hash is verifiable
# by stdlib crypt() (this is the whole point of the fallback path).
import crypt as _crypt
_LEGACY_MD5_HASH = _crypt.crypt("12345", "$1$abcdefghijkl")


