def _patch_connect(monkeypatch, cursor):
    """Patch ``database.connect`` to yield a ``_SpyConn(cursor)``."""

    @contextlib.contextmanager
    def _cm(*a, **kw):
        conn = _SpyConn(cursor)
        try:
            yield conn
        except BaseException:
            conn.rollback()
            raise

    monkeypatch.setattr(database, "connect", _cm)


