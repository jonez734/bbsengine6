def test_checkpassword_no_pg_crypt_round_trip(args, monkeypatch, echo_calls):
    """checkpassword must NOT issue a SELECT containing ``crypt(``.

    The pre-2026-08-23 code emitted
    ``select 1 from ... where password=crypt(%s, password)``.
    After the local-verify rewrite the verify runs entirely in
    Python; the only SELECT is the row fetch for the stored hash.
    """
    cursor = _SpyCursor(stored_password=_HEALTHY_BCRYPT_HASH)
    _patch_connect(monkeypatch, cursor)

    libmember.checkpassword(args, "12345", membermoniker="jam", pool=Mock())

    for query, _params in cursor.calls:
        rendered = (
            query.as_string(None)
            if hasattr(query, "as_string")
            else str(query)
        ).lower()
        assert "crypt(" not in rendered, (
            f"checkpassword must not contain crypt() in SQL (PG round-trip "
            f"removed); got: {rendered!r}"
        )


